import { _electron as electron } from "playwright-core";
import fs from "fs";
// Picking your deck from a drop-down on Lobbies, Find a match and Ranked: it sets the deck every table setup starts with.
const OUT = process.argv[2] || "shots-pick";
fs.mkdirSync(OUT, { recursive: true });
const prof = "/tmp/bounty-prof-pick"; fs.rmSync(prof, { recursive: true, force: true });
const app = await electron.launch({ executablePath: "node_modules/electron/dist/electron", args: ["--no-sandbox", "dist/kit/app"], env: { ...process.env, BOUNTY_PROFILE: prof } });
const page = await app.firstWindow(); const errs = [];
page.on("pageerror", e => errs.push(String(e)));
page.on("console", m => { if (m.type() === "error" && !/peerjs\.com|ERR_CONNECTION|40[034]/.test(m.text())) errs.push(m.text()); });
await page.setViewportSize({ width: 1280, height: 900 }).catch(() => {});
await page.waitForLoadState("load"); await page.waitForTimeout(1500);
let fail = 0;
const check = (ok, msg) => { console.log(ok ? "ok  " : "FAIL", msg); if (!ok) fail++; };
const wait = ms => page.waitForTimeout(ms);
const list = cs => cs.map(c => "4x" + c).join("\n").replace(/4x(\S+)$/, "2x$1");
const sabo = list(["OP05-003","OP05-004","OP05-006","OP05-007","OP05-009","OP05-010","OP05-011","OP05-013","OP05-015","OP05-016","OP05-017","OP05-018","OP05-019"]);
const zoro = list(["OP01-013","OP01-016","OP01-024","OP01-014","OP01-015","OP01-017","OP01-018","OP01-019","OP01-020","OP01-021","OP01-022","OP01-025","OP01-026"]);
await page.evaluate(([a, b]) => {
  localStorage.setItem("nakama:decks", JSON.stringify([{id: "d1", name: "Sabo", leader: "OP05-001 Sabo", deck: a, life: 5}, {id: "d2", name: "Old Zoro", leader: "OP01-001 Roronoa Zoro", deck: b, life: 4, sleeve: 2}]));
  localStorage.setItem("nakama:setup", JSON.stringify({nick: "Ryan", leader: "OP05-001 Sabo", deck: a, life: 5}));
}, [sabo, zoro]);
await page.reload(); await wait(1500);
await page.evaluate(() => openLobbies()); await wait(500);
const b0 = await page.evaluate(() => ({opts: [...document.querySelectorAll("#deckpick option")].map(o => o.textContent), sel: $("#deckpick").value}));
console.log("lobbies", JSON.stringify(b0));
check(b0.opts.length === 2 && b0.opts[0] === "Old Zoro (50 cards)" && b0.sel === "d1", "Lobbies has a drop-down of your saved decks, on the one you play");
await page.selectOption("#deckpick", "d2"); await wait(300);
const v = await page.evaluate(() => loadSaved());
check(v.leader.startsWith("OP01-001") && v.deck.startsWith("4xOP01-013") && v.life === 4 && v.sleeve === 2 && v.did === "d2" && v.nick === "Ryan", "picking one makes it your deck, keeping your name");
await page.screenshot({ path: OUT + "/lobbies.png" });
await page.click('[data-do="lbmake"]'); await wait(500);
check(await page.evaluate(() => $("#f-leader").value.startsWith("OP01-001") && $("#f-deck").value.startsWith("4xOP01-013")), "making a lobby starts with that deck");
await page.evaluate(() => { closeModal(); openQuick(); }); await wait(400);
const q = await page.evaluate(() => ({sel: $("#deckpick").value, bad: ($(".rkbad") || {}).textContent || ""}));
console.log("find a match", JSON.stringify(q));
check(q.sel === "d2" && /aren't legal in Standard/.test(q.bad), "Find a match shows the same deck, and says it isn't legal in Standard");
await page.selectOption("#deckpick", "d1"); await wait(300);
check(await page.evaluate(() => !$(".rkbad") && loadSaved().did === "d1"), "switching back there clears the warning");
// a deck that isn't saved shows as it is
await page.evaluate(() => { const v = loadSaved(); v.deck = v.deck.replace("4xOP05-003", "3xOP05-003"); save(v); closeModal(); openRanked(); }); await wait(400);
const r = await page.evaluate(() => ({first: $("#deckpick option").textContent, sel: $("#deckpick").value, n: document.querySelectorAll("#deckpick option").length}));
console.log("ranked", JSON.stringify(r));
check(r.sel === "" && /^OP05-001 Sabo, 49 cards$/.test(r.first) && r.n === 3, "an unsaved deck shows as the current one in Ranked");
console.log("errors", JSON.stringify(errs));
check(!errs.length, "no page errors");
await app.close();
console.log(fail ? `${fail} FAILED` : "all passed");
process.exit(fail ? 1 : 0);
