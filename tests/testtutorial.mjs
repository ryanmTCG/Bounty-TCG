import { _electron as electron } from "playwright-core";
import fs from "fs";
// The new-player tutorial: a guided game against the computer. Each step lights up where to act and moves on
// once it's done: keep the hand, play with DON!!, end the turn, play a Blocker, give DON!!, attack, defend.
const OUT = process.argv[2] || "shots-tutorial";
fs.mkdirSync(OUT, { recursive: true });
const prof = "/tmp/bounty-prof-tut"; fs.rmSync(prof, { recursive: true, force: true });
const app = await electron.launch({ executablePath: "node_modules/electron/dist/electron", args: ["--no-sandbox", "dist/kit/app"], env: { ...process.env, BOUNTY_PROFILE: prof } });
const page = await app.firstWindow();
const errs = [];
page.on("pageerror", e => errs.push(String(e)));
await page.setViewportSize({ width: 1500, height: 950 }).catch(() => {});
await page.waitForLoadState("load");
await page.waitForTimeout(1500);
let fail = 0;
const check = (ok, msg) => { console.log(ok ? "ok  " : "FAIL", msg); if (!ok) fail++; };
const coach = () => page.evaluate(() => { const el = document.querySelector("#coach"); return {shown: !el.hidden, h: (el.querySelector("h3") || {}).textContent || "", p: (el.querySelector("p:not(.cstep)") || {}).textContent || "", step: TUT ? TUT.i : null, hl: [...document.querySelectorAll(".coachhl")].map(e => e.dataset.do || e.dataset.src || e.dataset.opp || e.dataset.don || e.className.split(" ")[0])}; });
const waitStep = async (title, ms = 20000) => { const t0 = Date.now(); let c; while (Date.now() - t0 < ms) { c = await coach(); if (c.h === title) return c; await page.waitForTimeout(250); } console.log("stuck at", JSON.stringify(c)); return c; };
const clear = () => page.evaluate(() => { while (fxCur) { fxQueue.length = 0; fxFinish(false); } if (modal && modal.type !== "home") closeModal(); closeMenu(); render(); });

check(!!await page.$('[data-do="tutorial"]'), "a new player sees Learn to play on the home page");
await page.click('[data-do="tutorial"]');
await page.waitForTimeout(800);
let c = await coach();
console.log("start", JSON.stringify(c));
check(c.shown && c.h === "Welcome aboard", "the tutorial opens with its coach panel");
check(await page.evaluate(() => PR && PR.bot === 1 && S.first === true && S.hand.some(c => c.c === "OP01-016") && S.hand.some(c => c.c === "OP03-010")), "you play the computer, go first, and hold Nami and Fossa");
await page.click('[data-do="tutnext"]');
c = await waitStep("Your opening hand");
check(c.hl.includes("keep"), "the Keep button is lit up");
await page.waitForTimeout(800);
await page.click('[data-do="keep"]');
c = await waitStep("DON!! pay for cards");
check(c.hl.length === 1 && /^hand:/.test(c.hl[0]), "Nami is lit up in your hand");
// play Nami from the card menu, then skip her search
await page.click(`#hand [data-src="${c.hl[0]}"]`);
await page.waitForTimeout(300);
await page.click('#menu button:has-text("Play to Character area")');
await page.waitForTimeout(1500);
await clear();
c = await waitStep("End your turn");
check(c.hl.includes("endturn"), "End turn is lit up");
await page.click('.turnbar [data-do="endturn"]');
c = await waitStep("The computer's turn", 3000);
console.log("waiting", JSON.stringify(c));
c = await waitStep("Play a Blocker");
check(c.h === "Play a Blocker" && await page.evaluate(() => S.myTurn && S.turn === 2 && oppM.tn === 1), "the computer took its first turn and handed it back");
await page.evaluate(() => moveCard("hand:" + S.hand.findIndex(c => c.c === "OP03-010"), "chars"));
await clear();
c = await waitStep("Give DON!! for power");
check(c.hl.includes("a") && c.hl.includes("ld"), "your DON!! and Leader are lit up");
await page.evaluate(() => moveDon({pool: "a"}, "ld"));
c = await waitStep("Attack!");
await page.evaluate(() => attackWith("ld", "ld"));
let t0 = Date.now();
while (Date.now() - t0 < 15000) { c = await coach(); if (c.h === "A hit" || c.h === "The computer defended") break; await page.waitForTimeout(250); }
console.log("result", JSON.stringify(c));
check(c.h === "A hit" || c.h === "The computer defended", "the tutorial explains how the attack went");
await page.click('[data-do="tutnext"]');
c = await waitStep("End your turn");
await page.click('.turnbar [data-do="endturn"]');
c = await waitStep("Defend");
t0 = Date.now();
while (Date.now() - t0 < 25000) { if (await page.evaluate(() => defending())) break; await page.waitForTimeout(250); }
await page.waitForTimeout(1500);
c = await coach();
console.log("defend", JSON.stringify(c));
await page.screenshot({ path: OUT + "/defend.png" });
check(/computer is attacking/.test(c.p) && c.hl.some(h => /^hand:/.test(h)) && c.hl.some(h => /dfresolve|dfdone/.test(h)), "when attacked, your Counter cards and the resolve button are lit up");
check(await page.evaluate(() => defending()), "the attack waits for you instead of resolving by itself");
const ctr = c.hl.find(h => /^hand:/.test(h));
await page.click(`#hand [data-src="${ctr}"]`);
await page.waitForTimeout(500);
check(await page.evaluate(() => { const d = myDefender(); return !!(d && d.bc > 0); }), "tapping a lit Counter card adds its power");
await page.click('#mid [data-do="dfresolve"], #mid [data-do="dfdone"]');
c = await waitStep("You've got the basics");
check(c.h === "You've got the basics", "resolving the attack finishes the lessons");
await page.click('[data-do="tutnext"]');
await page.waitForTimeout(400);
c = await coach();
check(!c.shown && c.step === null && await page.evaluate(() => localStorage.getItem("bounty:tut") === "1"), "Finish closes the coach and remembers the tutorial is done");
check(await page.evaluate(() => !!(PR && PR.bot)), "the game against the computer goes on");
await page.evaluate(() => openHome());
await page.waitForTimeout(300);
check(!await page.$('.homesheet [data-do="tutorial"], #modal [data-do="tutorial"]'), "the home page stops offering the tutorial");
check(!errs.length, "no page errors" + (errs.length ? ": " + errs.slice(0, 3).join(" / ") : ""));
await app.close();
console.log(fail ? `${fail} FAILED` : "all passed");
process.exit(fail ? 1 : 0);
