import { _electron as electron } from "playwright-core";
import fs from "fs";
// Ranked season rewards: a sleeve for each rank reached in any season, locked until then.
const OUT = process.argv[2] || "shots-rewards";
fs.mkdirSync(OUT, { recursive: true });
const prof = "/tmp/bounty-prof-rewards"; fs.rmSync(prof, { recursive: true, force: true });
const app = await electron.launch({ executablePath: "node_modules/electron/dist/electron", args: ["--no-sandbox", "dist/kit/app"], env: { ...process.env, BOUNTY_PROFILE: prof } });
const page = await app.firstWindow(); const errs = [];
page.on("pageerror", e => errs.push(String(e)));
page.on("console", m => { if (m.type() === "error" && !/peerjs\.com|ERR_CONNECTION|40[034]|raw\.githubusercontent|Failed to fetch|ERR_/.test(m.text())) errs.push(m.text()); });
await page.setViewportSize({ width: 1280, height: 900 }).catch(() => {});
await page.waitForLoadState("load"); await page.waitForTimeout(3500);
let fail = 0;
const check = (ok, msg) => { console.log(ok ? "ok  " : "FAIL", msg); if (!ok) fail++; };
const wait = ms => page.waitForTimeout(ms);
await page.evaluate(() => { localStorage.setItem("nakama:setup", JSON.stringify({nick: "Ryan", leader: "OP01-001", deck: "4xOP01-013", life: 5, sleeve: 9})); });
await page.evaluate(() => openSetup()); await wait(400);
const s0 = await page.evaluate(() => ({n: document.querySelectorAll(".sleeves .swatch").length, locked: [...document.querySelectorAll(".sleeves .swatch.locked")].map(b => +b.dataset.sl), sel: formSleeve}));
console.log("setup", JSON.stringify(s0));
check(s0.n === 10 && s0.locked.join() === "7,8,9" && s0.sel === 0, "the three reward sleeves are locked at first, and a saved locked sleeve falls back to Standard");
await page.click('.sleeves [data-sl="8"]', { force: true }); await wait(200);
check(await page.evaluate(() => formSleeve === 0 && /reach Warlord in Ranked/.test($("#toast").textContent)), "a locked sleeve says what unlocks it");
// a past season at Warlord unlocks Supernova and Warlord
await page.evaluate(() => { RANK.ps = {"2026q3": 650000}; RANK.b = 120000; achRun(); }); await wait(200);
const t = await page.evaluate(() => $("#toast").textContent);
console.log("toast", t);
check(/Supernova and Warlord sleeves/.test(t) && await page.evaluate(() => STATS.sv === 8 && sleeveOk(8) && !sleeveOk(9)), "reaching Warlord in a season unlocks both sleeves for good, and says so once");
await page.evaluate(() => { closeModal(); openSetup(); }); await wait(300);
await page.click('.sleeves [data-sl="8"]'); await wait(200);
check(await page.evaluate(() => formSleeve === 8 && $("#slname").textContent === "Warlord"), "an unlocked one can be picked");
await page.screenshot({ path: OUT + "/setup.png" });
check(await page.evaluate(() => { newGame(Object.assign(readForm(), {deck: "4xOP01-013"}), false); return S.sleeve === 8 && sleeveOf(9) === 0; }), "the table uses it, and a still locked one isn't used");
await page.evaluate(() => openProfile()); await wait(400);
check(await page.evaluate(() => document.querySelectorAll(".pfrew .rw.got").length === 2 && document.querySelectorAll(".pfrew .rw").length === 3), "Profile shows the season rewards");
await page.screenshot({ path: OUT + "/profile.png" });
console.log("errors", JSON.stringify(errs));
check(!errs.length, "no page errors");
await app.close();
console.log(fail ? `${fail} FAILED` : "all passed");
process.exit(fail ? 1 : 0);
